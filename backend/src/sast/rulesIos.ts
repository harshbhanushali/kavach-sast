/**
 * iOS rules that read the binary's strings, imported symbols and Objective-C selectors.
 *
 * An IPA has no source to match, so each rule names something a compiled binary does carry:
 * a symbol it imports (`_CC_MD5`), a selector it implements (`URLSession:didReceiveChallenge:
 * completionHandler:`), a SQL or format string it embeds. `allOf` rules look at the whole
 * string table at once, which is how "uses a challenge handler and never evaluates the
 * trust" can be said at all.
 *
 * Statically linked libraries put their own strings in the same table (SQLCipher alone adds
 * hundreds of SQL fragments), so patterns here avoid text a library would also contain.
 */
